"""Frozen benchmark evaluation: seal predictions first, score in a separate call.

The project's official test has already been used historically. This module
does not turn that public benchmark into an independent blind confirmation.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
import torch

from .vendor.cmapss import load_cmapss_train, CMAPSS_COLUMNS
from .data import split_units, preprocess_frames, fit_prior_frames, OUTER_SEED, sha256
from .model import ContrastPE
from .run import INPUT_KEYS, code_fingerprint, write_json, utc_now
from .queue import underlying
from .metrics import engine_statistics, summarize


def infer_checkpoint(path, arrays, device):
    # Only read checkpoints generated by this package, never arbitrary downloads.
    checkpoint = torch.load(path, map_location="cpu", weights_only=True)
    if checkpoint["code_sha256"] != code_fingerprint() or checkpoint["epoch"] != 80:
        raise ValueError(f"Checkpoint/protocol mismatch: {path}")
    model = ContrastPE(checkpoint["arm"], use_prior=checkpoint["use_prior"]).to(device)
    model.load_state_dict(checkpoint["state_dict"])
    model.eval()
    data = {k: torch.as_tensor(arrays[k], device=device) for k in INPUT_KEYS}
    with torch.no_grad():
        pred = torch.cat([model(*(data[k][ix] for k in INPUT_KEYS)) for ix in
                          torch.arange(len(arrays["unit"]), device=device).split(256)])
    values = pred.cpu().numpy()
    if not np.isfinite(values).all():
        raise ValueError("Non-finite official predictions; engines cannot be dropped")
    return values


def predict(args):
    root, data_root = Path(args.out), Path(args.data_root)
    support = json.loads((root/"analysis"/"support.json").read_text(encoding="utf-8"))
    promotion = json.loads((root/"analysis"/"promotion.json").read_text(encoding="utf-8"))
    if support["status"] != "SUPPORT_PASS" or support["code_sha256"] != code_fingerprint():
        raise ValueError("Freeze the method only after the support gate passes")
    dest = root/"official"
    dest.mkdir(exist_ok=True)
    if (dest/"sealed.json").exists():
        raise FileExistsError("Official predictions are already sealed; do not regenerate after scoring")
    rows, inputs = [], {}
    device = torch.device(args.device)
    references = dict(promotion["references"])
    references.update({s: [v["reference"]] for s, v in support["guard_comparisons"].items()})
    for subset, refs in references.items():
        labels = list(dict.fromkeys([promotion["candidate"]]+refs))
        train = load_cmapss_train(data_root, subset).sort_values(["unit", "cycle"]).reset_index(drop=True)
        test_path = data_root/f"test_{subset}.txt"
        test = pd.read_csv(test_path, sep=r"\s+", header=None).dropna(axis=1, how="all")
        if test.shape[1] != len(CMAPSS_COLUMNS):
            raise ValueError("Unexpected official sensor-table schema")
        test.columns = CMAPSS_COLUMNS
        test = test.sort_values(["unit", "cycle"]).reset_index(drop=True)
        inputs[subset] = {"train_sha256": sha256(data_root/f"train_{subset}.txt"),
                          "test_sensors_sha256": sha256(test_path)}
        for fold in range(5):
            train_ids, _ = split_units(train, fold)
            tr = train[train.unit.isin(train_ids)].reset_index(drop=True)
            _, arrays = preprocess_frames(tr, test, subset, fold, endpoints_only=True)
            arrays["prior"] = np.zeros((len(arrays["unit"]), 2), np.float32)
            if promotion["prior"] == "full":
                table = fit_prior_frames(tr, test, subset, OUTER_SEED+fold)
                fallback = float(tr.groupby("unit").cycle.max().median())
                arrays["prior"][:, 0] = [table[(int(u), min(int(t)//10*10, 200))]/250.
                    if t >= 50 else fallback/250. for u, t in zip(arrays["unit"], arrays["as_of"])]
            for seed in (101, 202, 303):
                predictions = {}
                for label in labels:
                    parts = underlying(label)
                    for part in parts:
                        if part not in predictions:
                            folder = root/subset/f"{part}_f{fold}_s{seed}_{promotion['prior']}"
                            receipt = json.loads((folder/"done.json").read_text(encoding="utf-8"))
                            if (receipt["train_sha256"] != inputs[subset]["train_sha256"]
                                or sha256(folder/"checkpoint.pt") != receipt["artifacts"]["checkpoint.pt"]):
                                raise ValueError("Checkpoint/raw training data has changed")
                            predictions[part] = infer_checkpoint(folder/"checkpoint.pt", arrays, device)
                    pred = predictions[parts[0]] if len(parts) == 1 else np.where(
                        arrays["as_of"] < 100, predictions[parts[0]], predictions[parts[1]])
                    rows.append(pd.DataFrame({"subset": subset, "label": label, "fold": fold,
                         "seed": seed, "unit": arrays["unit"], "end_cycle": arrays["as_of"], "y_pred": pred}))
    all_predictions = pd.concat(rows, ignore_index=True)
    all_predictions.to_csv(dest/"model_predictions.csv", index=False)
    ensemble = all_predictions.groupby(["subset", "label", "unit", "end_cycle"], as_index=False).agg(
        y_pred=("y_pred", "mean"), n_models=("y_pred", "size"))
    if not (ensemble.n_models == 15).all():
        raise ValueError("Every official prediction must contain all 5 folds x 3 seeds")
    ensemble.to_csv(dest/"ensemble_predictions.csv", index=False)
    write_json(dest/"sealed.json", {"sealed_at": utc_now(), "code_sha256": code_fingerprint(),
        "inputs": inputs, "prediction_sha256": sha256(dest/"ensemble_predictions.csv"),
        "model_predictions_sha256": sha256(dest/"model_predictions.csv"),
        "official_rul_labels_read_by_prediction_stage": False,
        "historically_used_public_benchmark": True, "prediction_clipping": False})
    print(f"Predictions sealed: {dest/'sealed.json'}")


def score(args):
    dest = Path(args.out)/"official"
    seal = json.loads((dest/"sealed.json").read_text(encoding="utf-8"))
    if seal["code_sha256"] != code_fingerprint():
        raise ValueError("Code/protocol changed after prediction sealing")
    if sha256(dest/"ensemble_predictions.csv") != seal["prediction_sha256"]:
        raise ValueError("Sealed predictions changed")
    p = pd.read_csv(dest/"ensemble_predictions.csv")
    rows, hashes = [], {}
    for subset, group in p.groupby("subset", sort=True):
        if sha256(Path(args.data_root)/f"test_{subset}.txt") != seal["inputs"][subset]["test_sensors_sha256"]:
            raise ValueError("Official sensor table changed after prediction sealing")
        path = Path(args.data_root)/f"RUL_{subset}.txt"
        y = np.loadtxt(path, dtype=np.float64).reshape(-1)
        hashes[subset] = sha256(path)
        truth = dict(enumerate(np.minimum(y, 125.), start=1))
        for label, frame in group.groupby("label", sort=True):
            if set(frame.unit) != set(truth):
                raise ValueError("Official engine population differs from the label file")
            frame = frame.assign(y_true=frame.unit.map(truth))
            stats = engine_statistics(frame)
            rows.append({"subset": subset, "label": label, **summarize(stats),
                         "nasa_sum": float(stats.nasa.sum()), "ensemble_members": 15})
    pd.DataFrame(rows).to_csv(dest/"official_metrics.csv", index=False)
    write_json(dest/"scored.json", {"scored_at": utc_now(), "truth_sha256": hashes,
         "prediction_sha256": seal["prediction_sha256"], "historically_used_public_benchmark": True,
         "scope": "All four official subsets, all engines, fixed 5-fold x 3-seed ensembles",
         "nasa_mean_and_sum_are_both_reported": True})
    print(pd.DataFrame(rows).to_string(index=False))


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--stage", choices=("predict", "score"), required=True)
    p.add_argument("--data-root", required=True)
    p.add_argument("--out", default="outputs")
    p.add_argument("--device", default="cuda")
    args = p.parse_args()
    (predict if args.stage == "predict" else score)(args)


if __name__ == "__main__":
    main()
